def pre_iv():
    """The 128-bit pre-IV: checksum XOR time stamp, and 32 random bits"""
    px = 6                      # px per bit, 128 bits across
    left, top, row, gap = 20, 34, 40, 24
    width = left + 128 * px + 20
    height = top + 2 * row + gap + 36
    body = []
    for b in (0, 32, 64, 96, 127):
        body.append(text(left + b * px + (px / 2 if b == 127 else 0), top - 10,
                         str(b), "small", "middle"))

    def cell(b0, bits, r, label, cls="box", tall=False, first="label"):
        x = left + b0 * px
        y = top + r * (row + gap)
        h = 2 * row + gap if tall else row
        body.append(rect(x + 1, y + 1, bits * px - 2, h - 2, cls, 3))
        lines = lines_of(label)
        y0 = y + h / 2 - (len(lines) - 1) * 7 + 4
        for k, line in enumerate(lines):
            body.append(text(x + bits * px / 2, y0 + 14 * k, line,
                             first if k == 0 else "small"))

    cell(0, 64, 0, "64-bit checksum of the whole packet", "hi")
    cell(64, 32, 0, "0x00")
    cell(0, 32, 1, "0x00")
    cell(32, 52, 1, "52-bit time stamp, µs", "hi")
    cell(84, 8, 1, "counter", first="small")
    cell(92, 4, 1, "F")
    cell(96, 32, 0, "32 pseudo-\nrandom bits", "box", tall=True)
    body.append(text(left + 48 * px, top + row + gap / 2 + 6, "XOR", "xor"))
    body.append(text(left + 64 * px, top + 2 * row + gap + 26,
                     "the two rows exclusive-ored, the random bits next to "
                     "them: then one SPECK block step makes the IV",
                     "small"))
    return svg(width, height, "The 128-bit pre-IV of header encryption",
               "The checksum, exclusive-ored with the time stamp, its counter "
               "and flags, next to 32 pseudo-random bits.", body)


PICTURES["header-encryption-preiv.svg"] = pre_iv()


